def _drtran(path):
    """logL, nu_k (k = 0..2) with s.e. (None if fixed at zero), gain, and the
    adequacy and exogeneity p-values of a drtran output."""
    txt = open(path, encoding="utf-8", errors="replace").read()
    logl = float(re.search(r"[Ll]og-likelihood\s*[:=]\s*(-?[\d.]+)", txt).group(1))
    nu = {}
    i = re.search(r"k\s+nu_k\s+std\.err", txt).start()
    for ln in txt[i:].splitlines()[2:]:
        m = re.match(r"\s+(\d+)\s+(-?[\d.]+)\s+([\d.]+)\s+-?[\d.]+\s+\|\s+(-?[\d.]+)\s+([\d.]+)", ln)
        if not m:
            break
        k, v, se, cum, cse = int(m[1]), *map(float, m.group(2, 3, 4, 5))
        nu[k] = (v, se if se > 0 else None)
        gain = (cum, cse)
    j = txt.index("ADEQUACY")
    m = re.search(r"Q\((\d+)\) = ([\d.]+)\s+\[[^\]]*\]\s+p-value = ([\d.]+)", txt[j:])
    adeq = (int(m[1]), float(m[2]), float(m[3]))
    m = re.search(r"Q\((\d+)\) = ([\d.]+)\s+p-value = ([\d.]+)", txt[j:])
    exog = (int(m[1]), float(m[2]), float(m[3]))
    return dict(logL=logl, nu=nu, gain=gain, adeq=adeq, exog=exog)


