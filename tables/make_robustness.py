def _fue(path):
    txt = open(path, encoding="latin-1").read()
    num = r"(-?\d+\.\d+)"
    par = {}
    for m in re.finditer(r"Omegas for deterministic variable (\d+):\n\s+" + num + r"\s+\(" + num, txt):
        par[f"w{m.group(1)}"] = (float(m.group(2)), float(m.group(3)))
    for m in re.finditer(r"Deltas for deterministic variable (\d+):\n\s+" + num + r"\s+\(" + num, txt):
        par[f"d{m.group(1)}"] = (float(m.group(2)), float(m.group(3)))
    m = re.search(r"Coefficients for regular AR factor 1:\n\s+" + num + r"\s+\(" + num + r"\)[^\n]*\n\s+"
                  + num + r"\s+\(" + num, txt)
    par["phi1"], par["phi2"] = (float(m.group(1)), float(m.group(2))), (float(m.group(3)), float(m.group(4)))
    m = re.search(r"Mean parameter \(mu\):\n\s+" + num + r"\s+\(" + num, txt)
    par["mu"] = (float(m.group(1)), float(m.group(2)))
    par["sigma"] = float(re.search(r"^sigma :\s+" + num, txt, re.M).group(1))
    par["logL"] = float(re.search(r"^logelf:\s+" + num, txt, re.M).group(1))
    par["JB"] = float(re.search(r"Jarque-Bera:\s+" + num, txt).group(1))
    res = []
    for L in txt.split("\n"):
        m = re.match(r"^\s*\d+\s+\d+/\d{4}.*?[|+@]\s*(-?\d+\.\d+)\s*$", L)
        if m:
            res.append(float(m.group(1)))
    par["res"] = np.array(res[:int(re.search(r"Observations:\s+(\d+)", txt).group(1))])
    return par


def _ljung_box(e, h, nparm):
    from scipy.stats import chi2
    n = len(e)
    e = e - e.mean()
    r = [np.sum(e[j:] * e[:-j]) / np.sum(e * e) for j in range(1, h + 1)]
    q = n * (n + 2) * sum(r[j - 1] ** 2 / (n - j) for j in range(1, h + 1))
    return q, float(chi2.sf(q, h - nparm))


