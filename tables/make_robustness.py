def tab_sens() -> str:
    """theta and the adjustment under each treatment of 2008."""
    base_lab = {"Baseline: steps in $G/Y$ (2008Q2) and GAP (2008Q4)": r"$\alpha$ free",
                r"Baseline, $p=2$": r"$\alpha$ free, $p=2$",
                r"Baseline, case 3": r"$\alpha$ free, Case~3"}
    rows_a, rows_b = [], []

    def two(lab, th, al, st, pv, mark=""):
        t, ts = _ev(th)
        a_, as_ = _ev(al)
        return [rf"\quad {lab} & {t} & {a_} & {f(st)}{_st(pv)}{mark} \\",
                rf" & {ts} & {as_} & [{f(pv, 3)}] \\[2pt]"]

    for lab, p, case, wx, free in SENS:
        G = fit(free)
        w = G["weakex_wald"].get(next(v for v in G["series"] if v.startswith("GY")))
        if wx:
            W = fit(wx)
            x, _, pv = lr(G, W)
            rows_a += two(r"$\alpha_{G/Y}=0$ (adopted)", W["theta"], W["a_gap"], x, pv, r"$^{\dagger}$")
        rows = two(base_lab.get(lab, lab), G["theta"], G["a_gap"], w[0], w[1])
        (rows_a if lab in base_lab else rows_b).extend(rows)
    rows = ([r"\multicolumn{4}{@{}l}{Panel A. Baseline: steps in $G/Y$ (2008Q2) and in the gap (2008Q4)} \\ \hline"]
            + rows_a + [r"\multicolumn{4}{@{}l}{Panel B. Other treatments of 2008, $\alpha$ free} \\ \hline"] + rows_b)
    head = [r" & & & $G/Y$ weakly \\",
            r"Specification & $\hat\theta$ & $\hat\alpha_{\text{GAP}}$ & exogenous \\",
            r" & (s.e.) & (s.e.) & [$p$] \\"]
    notes = (r"Bivariate $(G/Y\mid\text{GAP})$, $p=4$, Case~2 unless stated. Last column: Wald statistic of "
             r"$\alpha_{G/Y}=0$; $^{\dagger}$: LR in the adopted model. $^{*}$, $^{**}$: rejection at 10\,\%, 5\,\%.")
    return _table_std("tab:sensitivity", r"The estimate of $\theta$ under alternative treatments of 2008",
                      "@{}lccc@{}", head, rows, notes)


