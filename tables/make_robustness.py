def out_path(key: str, ext: str = ".out") -> str:
    if key in _REG:
        p = os.path.join(REPO, "build", "drvec", key, key + ext)
        orig = _REG[key]
    else:
        r = RUNS[key]
        p = os.path.join(REPO, "build", "analyses", r["dir"], r["name"], r["name"] + ext)
        orig = r["orig_out"]
    if os.path.exists(p):
        return p
    if SUITE:
        q = os.path.join(SUITE, orig[:-4] + ext)
        if os.path.exists(q):
            return q
    raise FileNotFoundError(f"{key}: run `make analyses` (or pass --suite); missing {p}")


def fit(key: str) -> dict:
    F = parse(out_path(key))
    s = F["series"]
    A, B = alpha_se(F), beta_se(F)
    gy = next(i for i, v in enumerate(s) if v.startswith("GY"))
    F["theta"] = (-B[gy][0][0], B[gy][0][1])
    F["a_gap"], F["a_gy"] = A[-1][0], A[gy][0]
    return F


def est(c, nd=3):
    v, se = c
    return f(v, nd) + (f" ({f(se, nd)})" if se is not None else "")


def lr(free, restr):
    x = 2 * (free["logL"] - restr["logL"])
    return x, free["npar"] - restr["npar"], chi2_p(x, free["npar"] - restr["npar"])


def table(label, caption, cols, head, rows, notes):
    return "\n".join(_HEAD + [
        r"\begin{table}\caption{" + caption + r"}\label{" + label + "}",
        r"\begin{singlespace}\begin{footnotesize}\begin{center}",
        r"\resizebox{\textwidth}{!}{\begin{tabular}{" + cols + "}", r"\thickhline",
        *head, r"\thickhline", *rows,
        r"\thickhline\end{tabular}}\end{center}\end{footnotesize}",
        r"\begin{footnotesize}\textbf{Notes:} " + notes,
        r"\end{footnotesize}\end{singlespace}\end{table}", ""])




def _st(p):
    return "$^{**}$" if p < 0.05 else "$^{*}$" if p < 0.10 else ""


def _ev(c, nd=3):
    """estimate and its s.e. for the line below"""
    v, se = c
    return f(v, nd), (f"({f(se, nd)})" if se is not None else "")


def _table_std(label, caption, cols, head, rows, notes):
    return "\n".join(_HEAD + [
        r"\begin{table}\caption{" + caption + r"}\label{" + label + "}",
        r"\begin{singlespace}\begin{footnotesize}\begin{center}\setlength{\tabcolsep}{4pt}",
        r"\begin{tabular}{" + cols + "}", r"\thickhline", *head, r"\thickhline", *rows,
        r"\thickhline\end{tabular}\end{center}\end{footnotesize}",
        r"\begin{footnotesize}\textbf{Notes:} " + notes,
        r"\end{footnotesize}\end{singlespace}\end{table}", ""])

