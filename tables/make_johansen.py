"""Appendix C: the conventional analysis -- Johansen's reduced-rank regression
with the short-run dynamics by OLS, on seasonally adjusted data.

    python tables/make_johansen.py

Data: data/quarterly.csv, 2003Q1-2019Q4, in logs. Seasonal adjustment: each
log series is differenced, its seasonal harmonics (annual pair and the
Nyquist term) are estimated by OLS on the differences and removed, and the
series is cumulated back from its first value. VECM with p = 2 lags in levels,
constant restricted to the cointegrating space (case 2), and impulse dummies
for 2008Q2 and 2008Q3 unrestricted (concentrated out).

Tables (output/tables/):
  tab_joh_rank      trace tests: bivariate (G/Y, GAP) and trivariate (PE, PU, G/Y)
  tab_joh_vecm      cointegrating vectors, adjustment, weak exogeneity
  tab_joh_valid     trivariate restrictions: A alpha_PU = 0, B beta_PU = -beta_PE, C both
  tab_joh_sens      the multiplier under the treatments of 2008, including the
                    2008Q2 step in G/Y (shift in the relation, impulse in the
                    differences) that the baseline of the paper uses
  tab_joh_prices    CPI, PCE and GDP deflator gaps
  tab_joh_diag      residual diagnostics

Critical values: Osterwald-Lenum (1992), constant restricted to the
cointegrating space; the impulse dummies do not change the limit distribution,
a step in the relation does (Johansen, Mosconi and Nielsen, 2000), so no rank
test is reported with the step.
"""
from __future__ import annotations

import os

import numpy as np
import pandas as pd
from scipy import stats

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(HERE)
OUT = os.path.join(REPO, "output", "tables")
_HEAD = [r"% Generated by tables/make_johansen.py -- do not edit."]

# Osterwald-Lenum (1992, Table 1*), trace, constant restricted: p - r -> (10 %, 5 %)
CV = {1: (7.52, 9.24), 2: (17.85, 19.96), 3: (32.00, 34.91)}


# ── data ────────────────────────────────────────────────────────────────────

def load():
    q = pd.read_csv(os.path.join(REPO, "data", "quarterly.csv"))
    d = pd.DataFrame({"date": q["date"]})
    d["GY"] = np.log(q["GY"])
    d["GAP"] = np.log(q["GAP"])
    d["PE"], d["PU"] = np.log(q["PE"]), np.log(q["PU"])
    d["GAPPCE"], d["GAPGDPD"] = np.log(q["GAPPCE"]), np.log(q["GAPGDPD"])
    return d


def harmonic_sa(x):
    """Remove the deterministic seasonality estimated on the first differences."""
    dx = np.diff(x)
    t = np.arange(1, len(x))
    X = np.column_stack([np.ones_like(t), np.cos(np.pi * t / 2), np.sin(np.pi * t / 2), np.cos(np.pi * t)])
    b = np.linalg.lstsq(X, dx, rcond=None)[0]
    return np.concatenate([[x[0]], x[0] + np.cumsum(dx - X[:, 1:] @ b[1:])])


def dummies(dates, impulses=("2008Q2", "2008Q3")):
    return np.column_stack([(dates == d).astype(float) for d in impulses]) if impulses else None


# ── Johansen ────────────────────────────────────────────────────────────────

def _resid(A, Z):
    return A - Z @ np.linalg.lstsq(Z, A, rcond=None)[0] if Z is not None and Z.shape[1] else A


class Johansen:
    """Y (T x M) in levels, p lags in levels, restricted constant (plus any
    restricted columns in `rest`), unrestricted columns in `unres`."""

    def __init__(self, Y, p=2, unres=None, rest=None, names=None):
        T, M = Y.shape
        dY = np.diff(Y, axis=0)
        n = T - p
        Z0 = dY[p - 1:]
        lev = [Y[p - 1:-1], np.ones((n, 1))]
        if rest is not None:
            lev.append(rest[p - 1:-1])
        Z1 = np.hstack(lev)
        Z2 = [dY[p - 1 - j:-j] for j in range(1, p)]
        if unres is not None:
            Z2.append(unres[p:])
        Z2 = np.hstack(Z2) if Z2 else None
        self.M, self.n, self.p, self.names = M, n, p, names
        self.Z0, self.Z1, self.Z2 = Z0, Z1, Z2
        self.R0, self.R1 = _resid(Z0, Z2), _resid(Z1, Z2)
        self.fit()

    def _S(self, R0, R1):
        n = self.n
        return R0.T @ R0 / n, R0.T @ R1 / n, R1.T @ R1 / n

    def _eig(self, R0, R1):
        S00, S01, S11 = self._S(R0, R1)
        L = np.linalg.cholesky(S11)
        Li = np.linalg.inv(L)
        A = Li @ S01.T @ np.linalg.solve(S00, S01) @ Li.T
        lam, V = np.linalg.eigh((A + A.T) / 2)
        o = np.argsort(lam)[::-1]
        return lam[o], Li.T @ V[:, o], S00, S01, S11

    def fit(self):
        self.lam, self.V, self.S00, self.S01, self.S11 = self._eig(self.R0, self.R1)
        self.trace = [-self.n * np.sum(np.log(1 - self.lam[r:self.M])) for r in range(self.M)]
        self.logdet00 = np.linalg.slogdet(self.S00)[1]

    def loglik(self, r):
        return -self.n / 2 * (self.logdet00 + np.sum(np.log(1 - self.lam[:r])))

    def vecm(self, r=1, norm=None):
        """beta normalised on variable `norm` (default the last), alpha, their s.e., Omega."""
        norm = self.M - 1 if norm is None else norm
        b = self.V[:, :r] / self.V[norm, :r]
        S00, S01, S11, n = self.S00, self.S01, self.S11, self.n
        bSb = b.T @ S11 @ b
        a = S01 @ b @ np.linalg.inv(bSb)
        Om = S00 - a @ bSb @ a.T
        se_a = np.sqrt(np.outer(np.diag(Om), np.diag(np.linalg.inv(bSb))) / n)
        free = [i for i in range(b.shape[0]) if i != norm]
        H = np.eye(b.shape[0])[:, free]
        P = S11 - S11 @ b @ np.linalg.inv(bSb) @ b.T @ S11
        cov = np.kron(np.linalg.inv(a.T @ np.linalg.solve(Om, a)), np.linalg.inv(H.T @ P @ H)) / n
        se_b = np.full(b.shape[0], np.nan)
        se_b[free] = np.sqrt(np.diag(cov))
        e = self.R0 - self.R1 @ b @ a.T
        return dict(beta=b[:, 0], se_beta=se_b, alpha=a[:, 0], se_alpha=se_a[:, 0], Omega=Om, resid=e)

    def lr_restricted(self, r=1, H=None, A=None):
        """LR of beta = H phi and/or alpha = A psi (A: columns spanning alpha)."""
        R0, R1 = self.R0, self.R1
        if H is not None:
            R1 = R1 @ H
        if A is None:
            lam = self._eig(R0, R1)[0]
            ll = -self.n / 2 * (self.logdet00 + np.sum(np.log(1 - lam[:r])))
        else:
            Ap = np.linalg.svd(A, full_matrices=True)[0][:, A.shape[1]:]   # A_perp
            Ra, Rb = R0 @ A, R0 @ Ap
            Ra_b, R1_b = _resid(Ra, Rb), _resid(R1, Rb)
            lam = self._eig(Ra_b, R1_b)[0]
            Sbb = Rb.T @ Rb / self.n
            Saab = Ra_b.T @ Ra_b / self.n
            # |S00| = |A'A|^-1 |Ap'Ap|^-1 |S_aa.b| |S_bb| for the rotation [A Ap]
            rot = np.linalg.slogdet(np.hstack([A, Ap]))[1]
            ll = -self.n / 2 * (np.linalg.slogdet(Sbb)[1] + np.linalg.slogdet(Saab)[1]
                                - 2 * rot + np.sum(np.log(1 - lam[:r])))
        return 2 * (self.loglik(r) - ll)


# ── diagnostics ─────────────────────────────────────────────────────────────

def ljung_box(e, h, nparm=0):
    n = len(e)
    e = e - e.mean()
    r = [np.sum(e[j:] * e[:-j]) / np.sum(e * e) for j in range(1, h + 1)]
    q = n * (n + 2) * sum(r[j - 1] ** 2 / (n - j) for j in range(1, h + 1))
    return q, stats.chi2.sf(q, h - nparm)


def hosking(E, h, nparm_lags):
    n, M = E.shape
    E = E - E.mean(0)
    C0i = np.linalg.inv(E.T @ E / n)
    q = 0.0
    for j in range(1, h + 1):
        Cj = E[j:].T @ E[:-j] / n
        q += np.trace(Cj.T @ C0i @ Cj @ C0i) / (n - j)
    q *= n * n
    df = M * M * (h - nparm_lags)
    return q, df, stats.chi2.sf(q, df)


def jb(e):
    s, k = stats.skew(e), stats.kurtosis(e)
    x = len(e) / 6 * (s ** 2 + k ** 2 / 4)
    return x, stats.chi2.sf(x, 2)


# ── LaTeX ───────────────────────────────────────────────────────────────────

def f(x, nd=3):
    if x is None or (isinstance(x, float) and np.isnan(x)):
        return "--"
    s = f"{x:.{nd}f}"
    if float(s) == 0:
        s = s.lstrip("-")
    return s.replace("-", "$-$")


def est(v, se, nd=3):
    return f(v, nd) + ("" if se is None or np.isnan(se) else f" ({f(se, nd)})")


def star(stat, c10, c5):
    return "$^{**}$" if stat > c5 else "$^{*}$" if stat > c10 else ""


def table(label, caption, cols, head, rows, notes):
    return "\n".join(_HEAD + [
        r"\begin{table}[htbp]\caption{" + caption + r"}\label{" + label + "}",
        r"\begin{singlespace}\begin{footnotesize}\begin{center}",
        r"\resizebox{\textwidth}{!}{\begin{tabular}{" + cols + "}", r"\thickhline",
        *head, r"\thickhline", *rows,
        r"\thickhline\end{tabular}}\end{center}\end{footnotesize}",
        r"\begin{footnotesize}\textbf{Notes:} " + notes,
        r"\end{footnotesize}\end{singlespace}\end{table}", ""])


NAMES = {"GY": r"$\ln G_t/Y_t$", "GAP": r"$\ln PE_t/PU_t$", "PE": r"$\ln PE_t$", "PU": r"$\ln PU_t$",
         "GAPPCE": r"PCE gap", "GAPGDPD": r"GDP deflator gap", "const": "constant", "step": "step 2008Q2"}
SPEC = (r"Johansen's reduced-rank regression, $p=2$ lags in levels, constant restricted "
        r"to the cointegrating space, impulse dummies for 2008Q2 and 2008Q3 unrestricted, on "
        r"series seasonally adjusted by harmonic regression on their first differences, "
        r"2003Q1--2019Q4.")


def main():
    d = load()
    dates = d["date"].to_numpy()
    sa = {k: harmonic_sa(d[k].to_numpy()) for k in ("GY", "GAP", "PE", "PU", "GAPPCE", "GAPGDPD")}
    D = dummies(dates)
    step = (pd.PeriodIndex(d["date"].str.replace("Q", "-Q"), freq="Q") >= pd.Period("2008Q2", "Q")).astype(float)[:, None]
    imp_step = np.diff(np.vstack([[0.0], step]), axis=0)

    def sys(vars_, unres=D, rest=None):
        return Johansen(np.column_stack([sa[v] for v in vars_]), 2, unres, rest, list(vars_))

    biv, tri = sys(("GY", "GAP")), sys(("PU", "GY", "PE"))
    os.makedirs(OUT, exist_ok=True)
    out = {}

    # rank
    rows = []
    for title, J in (("Bivariate $(G/Y,\\ \\text{GAP})$", biv), ("Trivariate $(PU,\\ G/Y,\\ PE)$", tri)):
        for r in range(J.M):
            c10, c5 = CV[J.M - r]
            rows.append(" & ".join([title if r == 0 else "", f"$r{'=' if r == 0 else r'\le'}{r}$",
                                    f(J.lam[r]), f(J.trace[r], 2) + star(J.trace[r], c10, c5),
                                    f(c10, 2), f(c5, 2)]) + r" \\")
        rows.append(r"\hline")
    out["tab_joh_rank"] = table(
        "tab:johansen", "Johansen's procedure: trace tests", "llcccc",
        [r"System & $H_0$ & Eigenvalue & Trace & 10\,\% c.v. & 5\,\% c.v. \\"], rows[:-1],
        SPEC + r" Critical values: \citet{osterwald1992}, constant restricted; $^{*}$, $^{**}$: "
        r"rejection at 10\,\%, 5\,\%.")

    # VECMs
    rows = []
    for title, J in (("Bivariate", biv), ("Trivariate", tri)):
        V = J.vecm(1)
        rows.append(r"\multicolumn{4}{l}{\textit{" + title + r", $r=1$}} \\ \hline")
        for i, v in enumerate(J.names):
            A = np.zeros((J.M, J.M - 1))
            A[[k for k in range(J.M) if k != i], :] = np.eye(J.M - 1)
            lr = J.lr_restricted(1, A=A)
            rows.append(" & ".join([NAMES[v], est(V["beta"][i], V["se_beta"][i]),
                                    est(V["alpha"][i], V["se_alpha"][i]),
                                    f"{f(lr, 2)} ($p$ {f(stats.chi2.sf(lr, 1))})"]) + r" \\")
        rows.append(" & ".join([NAMES["const"], f(V["beta"][J.M]), "", ""]) + r" \\ \hline")
        out.setdefault("_vecm", {})[title] = V
    out["tab_joh_vecm"] = table(
        "tab:vecm_joh", "Johansen's procedure: cointegrating vectors and adjustment", "lccc",
        [r"Variable & $\beta$ (s.e.) & $\alpha$ (s.e.) & LR $\alpha_i=0$ \\"], rows[:-1],
        SPEC + r" $\beta$ is normalised on the price gap (bivariate) or on $\ln PE_t$ "
        r"(trivariate); $\hat\theta$ is minus the coefficient on $\ln G_t/Y_t$. LR: weak "
        r"exogeneity of each variable, $\chi^2(1)$.")

    # trivariate restrictions (order PU, GY, PE, const)
    HB = np.array([[-1, 0, 0], [0, 1, 0], [1, 0, 0], [0, 0, 1]], float)   # beta_PU = -beta_PE
    A_pu = np.array([[0, 0], [1, 0], [0, 1]], float)                        # alpha_PU = 0
    tests = [("A", r"$\alpha_{PU}=0$ (weak exogeneity of $PU$)", dict(A=A_pu), 1),
             ("B", r"$\beta_{PU}=-\beta_{PE}$ (relative PPP)", dict(H=HB), 1),
             ("C", "A and B jointly", dict(A=A_pu, H=HB), 2)]
    rows = []
    for k, lab, kw, df in tests:
        lr = tri.lr_restricted(1, **kw)
        rows.append(" & ".join([k, lab, f(lr, 2), str(df), f(stats.chi2.sf(lr, df))]) + r" \\")
    out["tab_joh_valid"] = table(
        "tab:validation_joh", "Johansen's procedure: restrictions on the trivariate system",
        "llccc", [r"Test & $H_0$ & LR & df & $p$ \\"], rows,
        SPEC + r" LR against the unrestricted rank-one model.")

    # sensitivity: treatments of 2008
    variants = [("No dummies", None, None), ("Impulse dummies 2008Q2, 2008Q3 (baseline)", D, None),
                ("Dummies and the 2008Q2 step in $G/Y$", np.hstack([D, imp_step]), step)]
    rows = []
    for lab, U, Rs in variants:
        J = Johansen(np.column_stack([sa["GY"], sa["GAP"]]), 2, U, Rs, ["GY", "GAP"])
        V = J.vecm(1)
        tr = f(J.trace[0], 2) + star(J.trace[0], *CV[2]) if Rs is None else "--"
        A = np.array([[0.0], [1.0]])
        lr = J.lr_restricted(1, A=A)
        rows.append(" & ".join([lab, est(-V["beta"][0], V["se_beta"][0]),
                                est(V["alpha"][1], V["se_alpha"][1]), tr,
                                f(stats.chi2.sf(lr, 1))]) + r" \\")
    out["tab_joh_sens"] = table(
        "tab:sensitivity_joh", "Johansen's procedure: the treatment of 2008", "lcccc",
        [r"Specification & $\hat\theta$ & $\hat\alpha_{\text{GAP}}$ & Trace $r=0$ & WE $G/Y$, $p$ \\"],
        rows, SPEC.replace(r", impulse dummies for 2008Q2 and 2008Q3 unrestricted", "") +
        r" Bivariate $(G/Y,\ \text{GAP})$. The step enters the cointegrating relation and its "
        r"first difference the short-run dynamics; with it the trace test has another limit "
        r"distribution \citep{johansen_mosconi_nielsen2000} and is not reported. WE: LR of the "
        r"weak exogeneity of $G/Y$.")

    # alternative price measures
    rows = []
    for lab, g in (("CPI (baseline)", "GAP"), ("PCE deflator", "GAPPCE"), ("GDP deflator", "GAPGDPD")):
        J = sys(("GY", g))
        V = J.vecm(1)
        rows.append(" & ".join([lab, f(J.trace[0], 2) + star(J.trace[0], *CV[2]),
                                f(J.trace[1], 2) + star(J.trace[1], *CV[1]),
                                est(-V["beta"][0], V["se_beta"][0]), est(V["alpha"][1], V["se_alpha"][1])]) + r" \\")
    out["tab_joh_prices"] = table(
        "tab:robustness", "Johansen's procedure: alternative price measures", "lcccc",
        [r"Price gap & Trace $r=0$ & Trace $r\le1$ & $\hat\theta$ & $\hat\alpha_{\text{GAP}}$ \\"], rows,
        SPEC + r" Bivariate $(G/Y,\ \text{gap})$. 5\,\% critical values 19.96 ($r=0$) and 9.24 ($r\le1$).")

    # diagnostics
    rows = []
    for title, J in (("Bivariate", biv), ("Trivariate", tri)):
        E = out["_vecm"][title]["resid"]
        q, df, p = hosking(E, 8, J.p - 1)
        for i, v in enumerate(J.names):
            lb = ljung_box(E[:, i], 8)
            j = jb(E[:, i])
            rows.append(" & ".join([title if i == 0 else "", NAMES[v], f"{f(lb[0], 2)} ({f(lb[1])})",
                                    f"{f(j[0], 2)} ({f(j[1])})",
                                    f"{f(q, 2)} ({f(p)})" if i == 0 else ""]) + r" \\")
        rows.append(r"\hline")
    out["tab_joh_diag"] = table(
        "tab:diag", "Johansen's procedure: residual diagnostics", "llccc",
        [r"System & Equation & $Q(8)$ ($p$) & JB ($p$) & Hosking $Q(8)$ ($p$) \\"], rows[:-1],
        SPEC + r" $Q(8)$: Ljung--Box; JB: Jarque--Bera; Hosking: multivariate portmanteau, "
        r"$M^2(8-p+1)$ df.")

    for k, v in out.items():
        if k.startswith("_"):
            continue
        open(os.path.join(OUT, k + ".tex"), "w").write(v)
        print("written", k)
    for t in ("Bivariate", "Trivariate"):
        V = out["_vecm"][t]
        print(t, "beta", np.round(V["beta"], 3), "se", np.round(V["se_beta"], 3), "alpha", np.round(V["alpha"], 3))
    print("trace biv", np.round(biv.trace, 2), "tri", np.round(tri.trace, 2))


if __name__ == "__main__":
    main()
